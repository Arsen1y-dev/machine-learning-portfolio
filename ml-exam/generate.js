function heading1(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    children: [new TextRun({ text, bold: true, size: 28, font: "Arial" })],
    spacing: { before: 360, after: 120 },
  });
}

function heading2(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2,
    children: [new TextRun({ text, bold: true, size: 24, font: "Arial" })],
    spacing: { before: 240, after: 80 },
  });
}

function para(text, opts = {}) {
  return new Paragraph({
    children: [new TextRun({ text, font: "Arial", size: 22, ...opts })],
    spacing: { before: 80, after: 80 },
    alignment: AlignmentType.JUSTIFIED,
  });
}

function bold(text) {
  return new TextRun({ text, bold: true, font: "Arial", size: 22 });
}

function normal(text) {
  return new TextRun({ text, font: "Arial", size: 22 });
}

function mixedPara(runs, opts = {}) {
  return new Paragraph({
    children: runs,
    spacing: { before: 80, after: 80 },
    alignment: AlignmentType.JUSTIFIED,
    ...opts,
  });
}

function bullet(text) {
  return new Paragraph({
    children: [new TextRun({ text, font: "Arial", size: 22 })],
    spacing: { before: 40, after: 40 },
    indent: { left: 720, hanging: 360 },
    bullet: { level: 0 },
  });
}

function formulaLine(text) {
  return new Paragraph({
    children: [new TextRun({ text, font: "Courier New", size: 20, italics: true })],
    spacing: { before: 60, after: 60 },
    alignment: AlignmentType.CENTER,
  });
}

